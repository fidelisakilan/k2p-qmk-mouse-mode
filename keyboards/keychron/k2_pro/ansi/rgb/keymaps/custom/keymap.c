bool process_record_user(uint16_t keycode, keyrecord_t *record) {
    if (!record->event.pressed) {
        return true;
    }
    if (keycode == MOUSE_TOG) {
        layer_invert(MOUSE);
        return false;
    }
    // Esc leaves the mouse layer instead of being sent to the host
    if (keycode == KC_ESC && layer_state_is(MOUSE)) {
        layer_off(MOUSE);
        return false;
    }
    return true;
}

bool rgb_matrix_indicators_advanced_user(uint8_t led_min, uint8_t led_max) {
    if (!layer_state_is(MOUSE)) {
        return true;
    }
    for (uint8_t row = 0; row < MATRIX_ROWS; row++) {
        for (uint8_t col = 0; col < MATRIX_COLS; col++) {
            uint8_t led = g_led_config.matrix_co[row][col];
            if (led == NO_LED || led < led_min || led >= led_max) {
                continue;
            }
            bool active = keymap_key_to_keycode(MOUSE, (keypos_t){.row = row, .col = col}) != KC_TRNS;
            rgb_matrix_set_color(led, active ? 255 : 0, 0, 0);
        }
    }
    return false;
}

void keyboard_post_init_user(void) {
    rgb_matrix_mode_noeeprom(RGB_MATRIX_SOLID_COLOR);
    rgb_matrix_sethsv_noeeprom(RGB_MATRIX_DEFAULT_HUE, RGB_MATRIX_DEFAULT_SAT, RGB_MATRIX_DEFAULT_VAL);
}

#ifdef OS_DETECTION_ENABLE
// USB setup-packet fingerprinting only happens on a wired connection, so this
// stays a no-op over Bluetooth and the physical Mac/Win switch keeps control.
static layer_state_t os_default_layer(os_variant_t os) {
    switch (os) {
        case OS_MACOS:
        case OS_IOS:
            return 1UL << MAC_BASE;
        case OS_WINDOWS:
        case OS_LINUX:
            return 1UL << WIN_BASE;
        default:
            return 0;
    }
}

void matrix_scan_user(void) {
    if (get_transport() != TRANSPORT_USB) {
        return;
    }
    layer_state_t target = os_default_layer(detected_host_os());
    if (target && default_layer_state != target) {
        default_layer_set(target);
    }
}
#endif
